package towerofhanoi;

/**
 *  This enum creates positions associated with the three towers in the
 *  Tower of Hanoi puzzle;
 * 
 *  @author Simoni Behl
 *  @version Mar 18, 2025
 */
public enum Position {
    /**
     * The Left position that corresponds with the left tower
     */
    LEFT, 
    /**
     * The Center position that corresponds with the center tower
     */
    CENTER, 
    /**
     * The Right position that corresponds with the Right tower
     */
    RIGHT, 
    /**
     * The Default position that defaults to the center tower
     */
    DEFAULT;

}
